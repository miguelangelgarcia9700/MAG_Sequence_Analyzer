class Sequence: 
    """Store a DNA sequence and provide useful methods for its analysis.

    The class stores a DNA sequence together with optional transcript
    metadata, genomic coordinates, and reference sequence identifiers.
    
    The only essential input for an object of this class is the DNA
    sequence. The rest of the input information may or may not be necessary, 
    depending on the method of analysis used. If you want to know what
    parameters are needed by de desired method, consult its docstring.
    
    It provides methods for nucleotide composition analysis, restriction
    enzyme searches, automatic variant generation, splicing analysis (MaxEntScan
    and HEXplorer analysis), and ClinVar information screening.

    The input can be supplied independently or together with metadata obtained 
    from a SearchInfo object, which automatically generates the data (recomended).

    Attributes:
        sequence (str): DNA sequence to analyze.
        transcript (str | None): Ensembl transcript identifier.
        start_cdna (int | None): Starting cDNA coordinate represented by
            the sequence. Negative values represent 5'UTR
        end_cdna (int | str | None): Ending cDNA coordinate. A string such
            as '*100' may represent a 3' UTR coordinate.
        chromosome (str | None): Chromosome containing the genomic region.
        flank (int): Number of flanking nucleotides included at each end.
        coordinates (str | None): Original transcript coordinate
            specification.
        genomic_coordinates (dict | None): Dictionary of genomic coordinates,
            represented by 'start' and 'end' lists of exonic coordinates.
        strand (int | None): Transcript strand, usually 1 or -1.
        refseq_id (str | None): RefSeq transcript identifier, when available.
        species (str): Species used for sequence retrieval.
        mutated_sequences (dict | None): Cached dictionary of generated
            single-nucleotide variants. None indicates that variants have
            not yet been generated. This are generated by interval_mutator()
            and the dictionary has the following format {variant: sequence}
            
    All of this atributes can be called through self.atribute

    Raises:
        ValueError: If sequence is None.
        
    Notes:
        In all methods, explicit parameter values take precedence over the 
        corresponding stored atributes in the object.
    """
    #In this program, Sequence class stores the sequence retrieved from SearchInfo, alongside the rest of its available information
    def __init__(self, sequence=None, transcript=None, start_cdna=None, end_cdna=None, chromosome = None, flank=0, coordinates = None, genomic_coordinates=None, strand = None, refseq_id=None, species="human"):
        if sequence is None:
            raise ValueError("Sequence is required to create a Sequence object")
        self.sequence = sequence
        self.transcript = transcript
        self.start_cdna = start_cdna
        self.end_cdna = end_cdna
        self.chromosome = chromosome
        self.flank = flank
        self.coordinates = coordinates
        self.genomic_coordinates = genomic_coordinates
        self.strand = strand
        self.refseq_id = refseq_id
        self.species = species
        self.mutated_sequences = None
    
    def get_mutated_sequences(self): 
    #THIS IS AN AUXILIAR METHOD MEANT TO MAKE OTHER METHODS AHEAD MORE EFFICIENT (through lazy caching), NOT AN ANALYSIS.
        """Calls interval_mutator to generate all possible single-nucleotide polymorphisms.

        Mutations are generated only on the first call. Subsequent calls return 
        the cached results without repeating the computation, as it can be heavy.
        Thus, this method is a lazy caching inplementation to avoid overusing interval_mutator.

        Returns:
            dict[str, str]: A dictionary mapping each variant identifier to
            its corresponding mutated DNA sequence. {variant: sequence}
        """
        
        if self.mutated_sequences is None: #Only call self.interval_mutator when self.mutated_sequences=None, which means it hasn't been already used
            self.mutated_sequences = self.interval_mutator()
            
        return self.mutated_sequences
    
    def translate_dna_to_protein(self, dna_sequence=None, frame=0, table=1, stop_symbol="*", to_stop=False, gap="-"):
        """Translate a DNA sequence into one or more protein sequences.

        Uses Biopython's translation functionality to translate the supplied DNA
        sequence or, if none is supplied, the sequence stored in this object.

        If frame=0, translates the sequence in all three forward reading frames.
        Otherwise, translates only the requested frame. This method does not
        automatically calculate the reverse complement.

        Parameters:
            dna_sequence (str | None): DNA sequence to translate. If None, uses
                self.sequence.
            frame (int): Reading frame to use. Use 0 to translate all three
                forward frames, or 1, 2, or 3 to translate the respective frame.
            table (int): Biopython genetic code table identifier. Defaults to 1,
                which is the standard genetic code.
            stop_symbol (str): Character used to represent stop codons. (default='*')
            to_stop (bool): If True, stop translation at the first in-frame stop
                codon.
            gap (str): Character representing gaps during translation. (default='-')

        Returns:
            dict[str, str]: Protein translations keyed by frame, for example
            'frame_1', 'frame_2', and 'frame_3'. If a single frame is requested,
            the dictionary contains only that frame. {frame: translated_sequence}

        Raises:
            ValueError: If the DNA sequence is not a string, or if one of the
                translation parameters has an invalid value.
        """
        return translate_dna_to_protein(self, dna_sequence, frame, table, stop_symbol, to_stop, gap)
        
    def nucleotide_proportion(self, nucleotide=None, sequence=None, return_as_percentage=False):
        """Calculate the proportion of a nucleotide in a DNA sequence.

        Counts the occurrences of the requested nucleotide and calculates its
        proportion relative to the sequence length.

        Parameters:
            nucleotide (str): Nucleotide to count. Must be A, C, G, or T.
            sequence (str | None): Sequence to analyze. If None, uses
                self.sequence.
            return_as_percentage (bool): If True, returns a percentage string;
                otherwise, returns a proportion between 0 and 1. Defaults to False.

        Returns:
            float | str: The proportion rounded to two decimal places, or a
                percentage string such as '20.0%'.

        Raises:
            ValueError: If the nucleotide is not supported or
                return_as_percentage is not a boolean.
        """
        return nucleotide_proportion(self, nucleotide, sequence, return_as_percentage)
    
    def cg_content(self, sequence=None, return_as_percentage=False): 
        """Calculate the GC content of a DNA sequence.

        Calculates the proportion of guanine (G) and cytosine (C) nucleotides
        relative to the sequence length.

        Parameters:
            sequence (str | None): Sequence to analyze. If None, uses
                self.sequence.
            return_as_percentage (bool): If True, returns a percentage string;
                otherwise, returns a proportion between 0 and 1. Defaults to False.

        Returns:
            float | str: The GC proportion rounded to two decimal places, or a
                percentage string such as '50.0%'.

        Raises:
            ValueError: If return_as_percentage is not a boolean or no sequence
                is available.
        """
        return cg_content(self, sequence, return_as_percentage)
    
    def cpg_islands(self, sequence=None):
        """Search for potential CpG islands in a DNA sequence.

        Scans the sequence using overlapping windows of 300 nucleotides, moving
        the window by 50 nucleotides each time. A window is considered a candidate
        CpG island when its GC content is at least 50% and its observed-to-expected
        CpG ratio is at least 0.6. Consecutive qualifying windows are merged.

        Parameters:
            sequence (str | None): Sequence to analyze. If None, uses
                self.sequence.

        Returns:
            str: A message containing the detected intervals in local, 1-based
                coordinates with the first nucleotide of the sequence being position 1. 
                Or a message indicating that no CpG island was found.

        Raises:
            ValueError: If no sequence is available.

        Notes:
            The window size, step size, and thresholds are currently defined
            inside the method.
        """
    #According to 2013, Brenner's Encyclopedia of Genetics, a CpG island must have a length >= 200, C+G content >=50% and an observed/expected CpG ratio >= 0.6
    #CpG ratio might be diluted in very long sequences, thus, the program will take windows of 300 nucleotides (Arbitrary size > 200, user may change it at will)
    #Which will slide 50 nucleotides between them (Arbitrary size, user may change it at will)
        return cpg_islands(self, sequence)
    
    def inputed_enzymes_search(self, sequence=None, enzymes=None, file_output=None, file_name=None, file_path="./results/inputed_enzymes_search"): 
        """Search inside a DNA sequence for restriction sites of user-selected enzymes.

        Uses Biopython's RestrictionBatch and Analysis classes to identify the
        cutting positions of the specified restriction enzymes. 
        
        Optionally writes the results to a CSV file inside a "results" directory
        created locally.

        Parameters:
            enzymes (list[str] | tuple[str, ...]): Restriction enzyme names
                recognized by Biopython.
            file_output (str | None): Set to 'csv' (file_output='csv') to write 
                the results to a CSV file. If None, no external file is written, but
                the result can still be stored in a variable or printed in the teminal.
            file_name (str | None): Set the name to the csv. If not set, default can be:
                'Inputed_enzymes_search' if self.transcript is empty
                "{self.transcript}_'Inputed_enzymes_search'" if self.transcript not empty
                "{self.transcript}_{self.coordinates}_'Inputed_enzymes_search'" if neither
                self.transcript nor self.coordinates are empty
            file_path(str): Route where the output file/s will be created.
                Default to "./results/inputed_enzymes_search"
                This are directories, the file name will be concatenated after

        Returns:
            dict | str: A dictionary mapping enzyme names to their cutting
                positions, or a message if no enzymes were found, or an error
                message if Biopython raises a ValueError during the search.
            csv file: A csv file inside a 'results' directory created locally
                if file_output was set to 'csv'

        Raises:
            ValueError: If file_output has an unsupported value. Or if no
                restriction enzymes have been inputed in the parameters.

        Notes:
            The method returns the results dictionary even when CSV output 
            is requested.
        """
        return inputed_enzymes_search(self, sequence, enzymes, file_output, file_name, file_path)
    
    def screen_enzymes(self, sequence=None): 
        """Search for restriction sites of a predefined set of enzymes.

        Uses Biopython to identify cutting positions for eight commonly used
        restriction enzymes: EcoRI, BamHI, HindIII, XhoI, XbaI, PstI, KpnI,
        and NotI.

        Parameters:
            sequence (str | None): Sequence to analyze. If None, uses
                self.sequence.

        Returns:
            dict: A dictionary mapping each restriction enzyme to its cutting
                positions, as returned by Biopython.

        Raises:
            ValueError: If no sequence is available.

        Notes:
            Results are returned in the terminal, but are not exported to a file,
            unlike in inputed_enzymes_search
        """
        return screen_enzymes(self, sequence)
    
    def search_seq(self, sequence=None, fragment=None): 
        """Search for a user-supplied pattern within a DNA sequence.

        Uses Python regular expressions to locate matches without distinguishing
        between uppercase and lowercase letters.

        Parameters:
            sequence (str | None): Sequence to search into. If None, uses
                self.sequence.
            fragment (str | None): Regular expression representing the pattern
                to search for.

        Returns:
            dict[str, str] | str: A dictionary containing each match and its
                local, 1-based start and end positions, with the first nucleotide 
                of the sequence being position 1. {match_n: 1-based_interval}

        Raises:
            ValueError: If no sequence is available.
        """
        return search_seq(self, sequence, fragment)
            
    def interval_mutator(self, transcript=None, start_cdna=None, end_cdna=None, genomic_coordinates=None, include_flanking=True, strand=None, intron_HGVS_limit=15, file_output=None, file_name=None, file_path="./results/interval_mutator"): 
    #intron_HGVS_limit was set to 15 because, usually, normal functioning introns wont be smaller than 30 nucleotides.
        """Generate all possible single-nucleotide polymorphisms in a sequence.

        For every nucleotide in the selected sequence, generates the three
        alternative nucleotide substitutions and stores each mutated sequence
        in a dictionary. When sufficient transcript and genomic metadata are
        available, variants are labelled using cDNA/HGVS-style notation.
        Otherwise, generic position labels are used.

        Flanking regions can be excluded from the generated variants. Intronic
        positions are described using HGVS-style intronic notation up to the
        specified limit; positions farther inside an intron receive generic
        intronic labels.
        
        Optionally writes the results to a CSV file, a fasta file or both 
        inside a "results" directory created locally.
        (check parameter file output)

        Parameters:
            transcript (str | None): Transcript ensembl identifier.
                If None, uses self.transcript.
            start_cdna (int | None): Starting cDNA coordinate of the interval.
                If None, uses self.start_cdna. If negative, indicates 5'UTR pressence
            end_cdna (int | str | None): Ending cDNA coordinate of the interval.
                If None, uses self.end_cdna. A string such as '*100' indicates 3' UTR.
            genomic_coordinates (dict | None): Genomic coordinates of the
                exons, containing 'start' and 'end' coordinate lists. 
                If None, uses self.genomic_coordinates.
            include_flanking (bool): If True, includes available flanking
                nucleotides in the mutation analysis. Defaults to True
            strand (int | None): Transcript strand (1 or -1)
                If None, uses self.strand.
            intron_HGVS_limit (int): Maximum intronic distance from an exon
                boundary described using HGVS-style notation. Defaults to 15.
            file_output (str | list[str] | tuple[str, ...] | None): Optional
                output format: 'csv', 'fasta', or a list/tuple containing both.
                example: file_output='csv' or 'fasta' or ['csv', 'fasta']
            file_name (str | None): Set the name to the csv. If not set, default can be:
                'Interval_mutator' if self.transcript is empty
                "{self.transcript}_'Interval_mutator'" if self.transcript not empty
                "{self.transcript}_{self.coordinates}_'Interval_mutator'" if neither
                self.transcript nor self.coordinates are empty
            file_path(str): Route where the output file/s will be created.
                Default to "./results/interval_mutator"
                This are directories, the file name will be concatenated after

        Returns:
            dict[str, str]: A dictionary mapping variant labels to their
                corresponding mutated DNA sequences. {Variant: Mutated_sequence}

        Raises:
            ValueError: If the output format is unsupported or the intronic
                notation limit is less than 1.

        Notes:
            The method returns the results dictionary even when CSV and/or fasta
            output is requested.
        """
        return interval_mutator(self, transcript, start_cdna, end_cdna, genomic_coordinates, include_flanking, strand, intron_HGVS_limit, file_output, file_name, file_path) 

    def hexplorer_splicing_analysis(self, hex_score_matrix, reference_sequence=None, mutated_sequences=None, file_output=None, file_name=None, file_path="./results/hexplorer_splicing_analysis"):
        """Evaluate potential splicing-regulatory effects of single-nucleotide variants.

        Calculates the HEXplorer ΔHZEI score for variants in a DNA sequence.
        This ΔHZEI can either be positive or negative. The more positive, the more likely 
        is for the mutated sequence to have generated new enhancer sites around the mutation
        The more negative it is, the more likely is for the mutated sequence to have 
        generated new silencer sites around the mutation.

        If you want to study the whole inputed coordinates, you must include a flanking of 
        AT LEAST 11(RECOMENDED). If not, the first and last 11 instances will not be reliable
        Every flanking possition will be cut off the results, as its only use in here is to 
        offer enough context for the interval to be correctly analyzed.

        The analysis uses the supplied reference sequence and mutated sequences,
        either inputed in this method parameters, or present in the class atributes
        (for example, the mutated sequences are obtainde by default by interval_mutator()
        and the default reference is self.sequence)

        Optionally writes the results to a CSV file inside a "results" directory
        created locally.

        Parameters:
            hex_score_matrix: Score matrix required by the HEXplorer scoring
                function. Contains a score for each possible hexamer
            reference_sequence (str | None): Reference DNA sequence used for
                comparison. If None, the method uses self.sequence.
            mutated_sequences (dict[str, str] | None): Dictionary mapping variant
                labels to mutated sequences. If None, the method uses
                self.mutated_sequences (obtained by interval_mutator).
            file_output (str | None): Optional csv output format
                May be introduced as a string (file_output='csv')
            file_name (str | None): Set the name to the csv. If not set, default can be:
                'HEXplorer_splicing_analysis' if self.transcript is empty
                "{self.transcript}_'HEXplorer_splicing_analysis'" if self.transcript not empty
                "{self.transcript}_{self.coordinates}_'HEXplorer_splicing_analysis'" if 
                neither self.transcript nor self.coordinates are empty
            file_path(str): Route where the output file will be created.
                Default to "./results/hexplorer_splicing_analysis".  
                This are directories, the file name will be concatenated after

        Returns:
            dict [str, float]: Returns a dictionary, mapping variant identifiers to
                their ΔHZEI scores. {Variant: ΔHZEI}
            float: If only one variant was introduced, the method will just return
                its ΔHZEI. 

        Notes:
            The score estimates changes in predicted splicing-regulatory
            potential; it should not be interpreted as direct experimental
            evidence of altered splicing.
            
            Both reference_sequence and mutated_sequences must be inputed
            in the parameters for them to be used. If only one has been inputed
            the program will ignore it and use the atribute equivalent instead.
            
            The score matrix for the hexamer scores is present in a dictionary 
            form inside a different module called hex_matrix
            
            The method returns the results dictionary even when CSV output
            is requested.
        """
        return hexplorer_splicing_analysis(self, hex_score_matrix, reference_sequence, mutated_sequences, file_output, file_name, file_path)
    
    def clinvar_screener(self, mutations=None, refseq_id=None, file_output=None, file_name=None, file_path="./results/clinvar_screener", mail="your_email@example.com"):
        """Retrieve ClinVar information for variants specified in HGVS notation.

        Queries the NCBI ClinVar database for each supplied variant and retrieves
        available information about its classification, clinical significance,
        molecular consequence, associated condition, and supporting submissions.
        
        Optionally writes the results to a CSV file inside a "results" directory
        created locally.

        Parameters:
            mutations (str | list[str] | dict[str, str] | None): A single variant,
                a list of variants, or a dictionary whose keys are variant labels
                (like the one obtained from interval_mutator).
                Variants must use the supported transcript-prefixed HGVS format,
                such as 'ENST00000357654:c.5193G>A' or 'NM_007294.4:c.5193G>A'. 
                If None, the method uses self.mutated_sequences which is obtained 
                by default through interval_mutator method.
            refseq_id (str | None): RefSeq transcript identifier used for ClinVar
                queries. If None, the program uses self.refseq_id. If self.refseq_id
                is empty too, the program will access Ensembl API REST to get it.
            file_output (str | None): Optional csv output format
                May be introduced as a string (file_output='csv')
            file_name (str | None): Set the name to the csv. If not set, default can be:
                'Clinvar_screener' if self.transcript is empty
                "{self.transcript}_'Clinvar_screener'" if self.transcript not empty
                "{self.transcript}_{self.coordinates}_'Clinvar_screener'" if neither 
                self.transcript nor self.coordinates are empty
            file_path(str): Route where the output file will be created.
                Default to "./results/clinvar_screener"
                This are directories, the file name will be concatenated after
            mail (str): Email address supplied to NCBI through Biopython Entrez.
                (NCBI requires a mail to access its database. Though, the generic
                one set as default ("your_email@example.com") works for some reason)

        Returns:
            list[dict]: A list containing a dictionary per variant. Each dictionary
            contains its respective variant's ClinVar information. 
            Returns an empty list if no variants are found.

        Raises:
            ValueError: If the mutation input or output format is invalid.

        Notes:
            This method makes requests to NCBI. Results depend on the records
            available in ClinVar at the time of the query. Variants not found
            in ClinVar are reported to the terminal and skipped.
            
            The method returns the results dictionary even when CSV output
            is requested.
        """
        return clinvar_screener(self, mutations, refseq_id, file_output, file_name, file_path, mail)
    
    def mes_canonical_analysis(self, genomic_coordinates = None, chromosome = None, strand = None, species = "human", coordinates = None, end_cdna = None, file_output=None, file_name=None, file_path="./results/mes_canonical_analysis"):
        """Evaluate canonical splice-site strength using MaxEntScan.
        
        The MaxEntScan score is a form of meassure for the splicing site strength

        Analyzes the acceptor and donor regions associated with the selected exons.
        For each analyzed splice site, calculates the percentage variation in the
        MaxEntScan score for every possible single-nucleotide polymorphism at the
        canonical positions.

        Exons whose splice sites fall within annotated 5' or 3' UTR regions are
        reported as being in UTR range rather than receiving the standard analysis.
        
        Optionally writes the results to a CSV file inside a "results" directory
        created locally.

        Parameters:
            genomic_coordinates (dict | None): Genomic coordinates of the
                exons, containing 'start' and 'end' coordinate lists. 
                If None, uses self.genomic_coordinates.
            chromosome (str | None): Chromosome containing the analyzed region.
                If None, uses self.chromosome.
            strand (int | None): Transcript strand (1 or -1). If None, uses
                self.strand or is attempted to be inferred from the exon coordinates.
            species (str): Species used for genomic sequence retrieval. Defaults
                to 'human', with the method using self.species when applicable.
            coordinates (str | None): Originally inputed coordinates, such as
                'ex.18', 'ex.18_20', or 'whole'. If None, uses self.coordinates.
                Only accepts exonic coordinates or 'whole', not cDNA coordinates.
            end_cdna (int | str | None): Ending cDNA coordinate, used to determine
                whether the selected interval includes a 3' UTR. If None, uses 
                self.end_cdna. If still None, the program assumes there is no 3'UTR
                If 3'UTR is detected, the program will asume it's the last exon
            file_output (str | None): Optional csv output format
                May be introduced as a string (file_output='csv')
            file_name (str | None): Set the name to the csv. If not set, default can be:
                'MES_canonical_analysis' if self.transcript is empty
                "{self.transcript}_'MES_canonical_analysis'" if self.transcript not empty
                "{self.transcript}_{self.coordinates}_'MES_canonical_analysis'" if 
                neither self.transcript nor self.coordinates are empty
            file_path(str): Route where the output file will be created.
                Default to "./results/mes_canonical_analysis"
                This are directories, the file name will be concatenated after

        Returns:
            dict [str, list]: A dictionary whose keys are the exons acceptors/donnors
                and whose values are lists with the description of the splicing-strength
                variation for every possible variant. 
                {exon_acceptor/donnor: [Variant_nt1>nt2 = % of strength variation, variant_nt1>nt3...]}

        Raises:
            ValueError: If required genomic metadata is unavailable, the
                coordinate specification is unsupported, or the output format
                is invalid.

        Notes:
            The method retrieves genomic sequence from Ensembl API REST and uses
            MaxEntScan scoring functions for acceptor and donor sites. 
            
            Percentage variations are relative to the reference score.
            
            The method returns the results dictionary even when CSV output
            is requested.
        """
        return mes_canonical_analysis(self, genomic_coordinates, chromosome, strand, species, coordinates, end_cdna, file_output, file_name, file_path)